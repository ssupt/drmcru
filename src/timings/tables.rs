//! Timing tables ported verbatim from CRU's `DetailedResolutionClass.cpp`.
//!
//! Each row is (active size, interlaced, refresh window in mHz, horizontal
//! front/sync/back porch, vertical front/sync/back porch in frame lines,
//! sync polarities).

pub(super) struct TableTiming {
    pub h_active: i64,
    pub v_active: i64,
    pub interlaced: bool,
    pub min_v_rate: i64,
    pub max_v_rate: i64,
    pub h: [i64; 3],
    pub v: [i64; 3],
    pub h_polarity: bool,
    pub v_polarity: bool,
}

#[allow(clippy::too_many_arguments)]
const fn t(
    h_active: i64,
    v_active: i64,
    interlaced: bool,
    min_v_rate: i64,
    max_v_rate: i64,
    h: [i64; 3],
    v: [i64; 3],
    h_polarity: bool,
    v_polarity: bool,
) -> TableTiming {
    TableTiming {
        h_active,
        v_active,
        interlaced,
        min_v_rate,
        max_v_rate,
        h,
        v,
        h_polarity,
        v_polarity,
    }
}

